import { chromium } from '/Users/justas/Desktop/mcp-accessibility-scanner/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 375, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://localhost:8768');
async function add(title) { await page.getByRole('textbox', { name: 'New todo', exact: true }).fill(title); await page.getByRole('button', { name: 'Add', exact: true }).click(); }
await add('<img src=x onerror=alert(1)>');
await add('second');
await page.getByRole('checkbox', { name: 'Complete second', exact: true }).check();
await page.getByRole('button', { name: 'Completed', exact: true }).click();
assert.equal(await page.getByTestId('todo').count(), 1);
assert.match(await page.getByTestId('remaining').textContent(), /1/);
await page.getByRole('button', { name: 'Edit second', exact: true }).click();
await page.getByRole('textbox', { name: 'Edit todo', exact: true }).fill('discard');
await page.getByRole('button', { name: 'Cancel', exact: true }).click();
assert.equal(await page.getByRole('checkbox', { name: 'Complete second', exact: true }).isChecked(), true);
await page.getByRole('button', { name: 'Edit second', exact: true }).click();
await page.getByRole('textbox', { name: 'Edit todo', exact: true }).fill('renamed');
await page.getByRole('button', { name: 'Save', exact: true }).click();
await page.reload();
assert.equal(await page.getByTestId('todo').count(), 2);
assert.equal(await page.locator('li img').count(), 0);
await page.getByRole('button', { name: 'Clear completed', exact: true }).click();
assert.equal(await page.getByTestId('todo').count(), 1);
await page.getByRole('button', { name: 'Delete <img src=x onerror=alert(1)>', exact: true }).click();
assert.equal(await page.getByTestId('todo').count(), 0);
await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('blocked'); }; });
await add('kept in memory');
assert.match(await page.getByRole('status').textContent(), /Saving failed/);
assert.equal(await page.getByTestId('todo').count(), 1);
await page.reload();
await page.evaluate(() => localStorage.clear());
await page.addInitScript(() => { Storage.prototype.getItem = () => { throw Error('blocked'); }; });
await page.reload();
assert.match(await page.getByRole('status').textContent(), /could not be loaded/);
await add('read failure still usable');
assert.equal(await page.getByTestId('todo').count(), 1);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
assert.deepEqual(errors, []);
await browser.close();
console.log('Browser checks passed at 375px: add, text safety, toggle/filter/count, cancel/save, reload, clear/delete, storage write/read failures, no overflow or page errors.');
