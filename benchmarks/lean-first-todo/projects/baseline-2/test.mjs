import assert from 'node:assert/strict';
import { initialState, transition, visibleTodos, parseStored } from './todo.mjs';
const empty = initialState();
assert.notEqual(empty.todos, initialState().todos);
let state = transition(empty, { type: 'add', title: '  same  ' });
state = transition(state, { type: 'add', title: 'same' });
assert.deepEqual(empty, { todos: [], nextId: 1 });
assert.equal(state.todos[0].title, 'same');
assert.equal(transition(state, { type: 'edit', id: 1, title: '  ' }), state);
assert.equal(transition(state, { type: 'add', title: ' ' }), state);
assert.equal(transition(state, { type: 'toggle', id: 44 }), state);
assert.equal(transition(state, { type: 'unknown', id: 1 }), state);
const toggled = transition(state, { type: 'toggle', id: 1 });
assert.equal(state.todos[0].completed, false);
assert.deepEqual(visibleTodos(toggled, 'active').map(t => t.id), [2]);
assert.deepEqual(visibleTodos(toggled, 'completed').map(t => t.id), [1]);
let edited = transition(toggled, { type: 'edit', id: 1, title: ' changed ' });
assert.equal(edited.todos[0].completed, true);
edited = transition(edited, { type: 'clearCompleted' });
edited = transition(edited, { type: 'remove', id: 2 });
assert.equal(transition(edited, { type: 'add', title: 'later' }).todos[0].id, 3);
assert.deepEqual(parseStored(JSON.stringify(toggled)), toggled);
for (const text of [null, '{', '{}', JSON.stringify({ ...state, nextId: 2 }), JSON.stringify({ ...state, todos: [state.todos[0], state.todos[0]] }), JSON.stringify({ todos: [{ id: 1, title: ' bad ', completed: false }], nextId: 2 })]) assert.deepEqual(parseStored(text), initialState());
const exhausted = { todos: [], nextId: Number.MAX_SAFE_INTEGER };
assert.equal(transition(exhausted, { type: 'add', title: 'x' }), exhausted);
console.log('Domain checks passed: immutability, parsing, identities, filters, edits, exhaustion.');
