import assert from 'node:assert/strict';
import {initialState, transition as go, parseStored, visibleTodos} from './todo.mjs';
const start = initialState();
let s = go(start,{type:'add', title:' One '});
s = go(s,{type:'add',title:'Two'});
s = go(s,{type:'remove',id:2});
s = go(s,{type:'add',title:'Three'});
assert.deepEqual(s.todos.map(t=>t.id),[1,3]); // same executable Lean trace
assert.deepEqual(start,initialState());
const frozen = structuredClone(s);
for (const action of [{type:'edit',id:1,title:'  '},{type:'remove',id:99},{type:'wat'},{type:'add',title:' '}]) assert.deepEqual(go(s,action),s);
assert.deepEqual(s,frozen);
s=go(s,{type:'toggle',id:1});
assert.equal(visibleTodos(s,'active').length,1);
assert.equal(visibleTodos(s,'completed')[0].id,1);
assert.equal(go(s,{type:'edit',id:1,title:' Updated '}).todos[0].completed,true);
assert.equal(go(s,{type:'clearCompleted'}).todos[0].id,3);
assert.deepEqual(parseStored(JSON.stringify(s)),s);
for (const bad of [null,'{','{}',JSON.stringify({...s,nextId:3}),JSON.stringify({...s,todos:[s.todos[0],s.todos[0]]}),JSON.stringify({...s,todos:[{...s.todos[0],title:' bad '}]})]) assert.deepEqual(parseStored(bad),initialState());
assert.deepEqual(go({todos:[],nextId:Number.MAX_SAFE_INTEGER},{type:'add',title:'No'}),{todos:[],nextId:Number.MAX_SAFE_INTEGER});
assert.notEqual(initialState().todos,initialState().todos);
console.log('PASS domain: identity trace, immutability, blank/no-op, filters, edits, clear, atomic parsing, exhaustion');
