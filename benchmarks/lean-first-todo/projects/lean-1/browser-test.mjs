import {chromium} from '/Users/justas/Desktop/mcp-accessibility-scanner/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
try {
const page=await browser.newPage({viewport:{width:375,height:812}});
await page.goto('http://127.0.0.1:8131');
const input=page.getByRole('textbox',{name:'New todo'});
await input.fill('<b>First</b>'); await input.press('Enter');
await input.fill('Second'); await page.getByRole('button',{name:'Add',exact:true}).click();
assert.equal(await page.locator('[data-testid=todo] b').count(),0);
await page.getByRole('checkbox',{name:'Complete <b>First</b>',exact:true}).check();
await page.getByRole('button',{name:'Edit <b>First</b>',exact:true}).click();
await page.getByRole('textbox',{name:'Edit todo',exact:true}).fill('Changed');
await page.getByRole('button',{name:'Cancel',exact:true}).click();
assert.equal(await page.getByRole('checkbox',{name:'Complete <b>First</b>',exact:true}).isChecked(),true);
await page.getByRole('button',{name:'Edit Second',exact:true}).click();
await page.getByRole('textbox',{name:'Edit todo',exact:true}).fill('Updated');
await page.getByRole('button',{name:'Save',exact:true}).click();
await page.getByRole('button',{name:'Active',exact:true}).click();
assert.equal(await page.locator('[data-testid=todo]').count(),1);
assert.match(await page.locator('[data-testid=remaining]').textContent(),/1/);
await page.reload();
assert.equal(await page.locator('[data-testid=todo]').count(),2);
await page.getByRole('button',{name:'Clear completed',exact:true}).click();
await page.getByRole('button',{name:'Delete Updated',exact:true}).click();
assert.equal(await page.locator('[data-testid=todo]').count(),0);
await page.evaluate(()=>Object.defineProperty(Storage.prototype,'setItem',{value(){throw new Error('blocked')}}));
await input.fill('Memory survives'); await input.press('Enter');
assert.match(await page.getByRole('status').textContent(),/Could not save/);
assert.equal(await page.locator('[data-testid=todo]').count(),1);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
const failed=await browser.newPage();
await failed.addInitScript(()=>Object.defineProperty(Storage.prototype,'getItem',{value(){throw new Error('blocked')}}));
await failed.goto('http://127.0.0.1:8131');
assert.match(await failed.getByRole('status').textContent(),/Storage is unavailable/);
console.log('PASS browser: add, safe text, complete, cancel, save, filters/count, reload, clear/delete, storage read/write failures, 375px overflow');
} finally { await browser.close(); }
