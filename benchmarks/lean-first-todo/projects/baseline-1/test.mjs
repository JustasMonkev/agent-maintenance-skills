import assert from 'node:assert/strict';
import { initialState, transition, parseStored, visibleTodos } from './todo.mjs';
const start = initialState();
assert.notEqual(start, initialState());
let state = transition(start, { type: 'add', title: '  Read  ' });
assert.deepEqual(start, { todos: [], nextId: 1 });
state = transition(state, { type: 'add', title: 'Read' });
assert.deepEqual(state.todos.map(t => t.id), [1, 2]);
assert.equal(transition(state, { type: 'add', title: ' ' }), state);
assert.equal(transition(state, { type: 'edit', id: 1, title: ' ' }), state);
state = transition(state, { type: 'toggle', id: 1 });
assert.deepEqual(visibleTodos(state, 'active').map(t => t.id), [2]);
assert.deepEqual(visibleTodos(state, 'completed').map(t => t.id), [1]);
state = transition(state, { type: 'edit', id: 1, title: ' Finished ' });
assert.equal(state.todos[0].completed, true);
assert.equal(state.todos[0].title, 'Finished');
state = transition(state, { type: 'clearCompleted' });
state = transition(state, { type: 'remove', id: 2 });
state = transition(parseStored(JSON.stringify(state)), { type: 'add', title: 'Next' });
assert.equal(state.todos[0].id, 3);
assert.equal(transition(state, { type: 'unknown' }), state);
assert.equal(transition(state, { type: 'toggle', id: 100 }), state);
for (const value of [null, '{', '{}', JSON.stringify({ todos: [{ id: 1, title: ' x', completed: false }], nextId: 2 }), JSON.stringify({ todos: [{ id: 1, title: 'x', completed: false }, { id: 1, title: 'y', completed: false }], nextId: 2 })]) assert.deepEqual(parseStored(value), initialState());
const exhausted = { todos: [], nextId: Number.MAX_SAFE_INTEGER };
assert.equal(transition(exhausted, { type: 'add', title: 'No' }), exhausted);
console.log('PASS domain: immutable transitions, identity, filtering, storage validation, exhaustion');
